def obtener_login_url():
    url_configurada = os.getenv("KORE_URL")
    if url_configurada:
        return url_configurada

    csv_path = PROJECT_ROOT / "data" / "kore_URL.csv"
    with csv_path.open(encoding="utf-8", newline="") as archivo:
        filas = csv.DictReader(archivo)
        for fila in filas:
            if fila.get("Pre") == "1" and fila.get("Contexto") == "login_home":
                url = (fila.get("URL") or "").strip()
                if url:
                    return url

    raise ValueError(
        "No se encontró KORE_URL en .env ni una URL Pre=1/login_home "
        "en data/kore_URL.csv"
    )


